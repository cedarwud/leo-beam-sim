export function formatSatCount(value: number): string {
  return `${value.toFixed(0)} sats`;
}

export function formatBeamCount(value: number): string {
  return `${value.toFixed(0)} beams`;
}

export function formatUeCount(value: number): string {
  return `${value.toFixed(0)} UEs`;
}

export function formatUeSpeed(value: number): string {
  return `${value.toFixed(0)} km/sec`;
}

export function formatWaypointCount(value: number): string {
  return `${value.toFixed(0)} waypoints`;
}

export function formatGridSpacing(value: number): string {
  return `${value.toFixed(0)} km`;
}

